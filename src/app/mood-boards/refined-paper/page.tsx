/* -------------------------------------------------------------- the card */
function Artifact({ n, item, wide }: { n: number; item: Item; wide?: boolean }) {
  const num = String(n).padStart(2, "0");
  const noteId = `rp-note-${num}`;
  // Static cards reveal the note on hover or focus of the whole card.
  // Interactive cards reveal it from the caption row, so it never covers a control in use.
  const trigger = item.interactive ? "group/cap" : "";
  const reveal = item.interactive
    ? "group-hover/cap:opacity-100 group-hover/cap:translate-y-0 group-focus-visible/cap:opacity-100 group-focus-visible/cap:translate-y-0"
    : "group-hover/card:opacity-100 group-hover/card:translate-y-0 group-focus-visible/card:opacity-100 group-focus-visible/card:translate-y-0";
  return (
    <figure
      className={`group/card relative mb-12 break-inside-avoid outline-none ${item.interactive ? "" : "rounded-[2px] focus-visible:ring-2 focus-visible:ring-[var(--ink)] focus-visible:ring-offset-4 focus-visible:ring-offset-[var(--paper)]"}`}
      tabIndex={item.interactive ? undefined : 0}
      aria-describedby={noteId}
    >
      <div className={`overflow-hidden ${item.img ? "border border-[var(--rule)] bg-[var(--mount)] p-2.5" : "border border-[var(--rule)]"} transition-[border-color] duration-300 group-hover/card:border-[var(--rule-strong)]`}>
        {item.img ? (
          <Image
            src={item.img.src}
            width={item.img.w}
            height={item.img.h}
            alt={item.img.alt}
            sizes={wide ? "(min-width: 1360px) 1280px, 100vw" : "(min-width: 1280px) 400px, (min-width: 768px) 46vw, 92vw"}
            className="h-auto w-full"
          />
        ) : (
          <div className={wide ? "bg-[var(--paper)] p-5 md:p-8" : ""}>{item.body}</div>
        )}
      </div>
      <figcaption
        className={`${trigger} relative mt-3 flex items-baseline gap-3 rounded-[2px] outline-none ${item.interactive ? "cursor-help focus-visible:ring-2 focus-visible:ring-[var(--ink)] focus-visible:ring-offset-2 focus-visible:ring-offset-[var(--paper)]" : ""}`}
        tabIndex={item.interactive ? 0 : undefined}
      >
        <span className="rp-mono shrink-0 text-[11px] tabular-nums text-[var(--muted)]">{num}</span>
        <span className="min-w-0 flex-1">
          <span className="rp-sans text-[13px] font-medium text-[var(--ink)]">
            {item.title}
            {item.gen && <span className="ml-1.5 text-[var(--ink)]" aria-label="generated by your agent">✦</span>}
          </span>
          <span className="rp-sans block text-[12px] text-[var(--muted)]">
            {item.kind}
            {item.source ? ` · ${item.source}` : ""}
            {item.interactive && <span className="rp-hint"> · hover or focus here for the note</span>}
          </span>
        </span>
        <NoteToggle
          id={noteId}
          className={`rp-note pointer-events-none absolute right-0 bottom-full left-0 z-20 mb-3 translate-y-1.5 rounded-[3px] border border-[var(--rule-strong)] bg-[var(--paper)]/[.97] p-4 opacity-0 shadow-[0_18px_40px_-24px_rgba(33,31,27,.45)] backdrop-blur-sm transition duration-300 ease-[cubic-bezier(.22,.61,.36,1)] ${reveal}`}
        >
          {(["take", "use", "leave"] as const).map((k) => (
            <span key={k} className="grid grid-cols-[3.25rem_1fr] gap-2 py-0.5">
              <span className="rp-mono pt-[3px] text-[10px] tracking-[0.08em] text-[var(--muted)] uppercase">{k === "use" ? "Where" : k}</span>
              <span className="rp-serif text-[14.5px] leading-[1.45] text-[var(--ink)]">{item.note[k]}</span>
            </span>
          ))}
        </NoteToggle>
      </figcaption>
    </figure>
  );
}

